    private static Dictionary<string, string> Merge(params Dictionary<string, string>[] parts)
    {
        var all = new Dictionary<string, string>(StringComparer.Ordinal);
        foreach (var part in parts)
        {
            foreach (var (english, slovak) in part)
            {
                if (!all.TryAdd(english, slovak))
                {
                    throw new InvalidOperationException($"Duplicate Slovak translation key: \"{english}\"");
                }
            }
        }

        return all;
    }

